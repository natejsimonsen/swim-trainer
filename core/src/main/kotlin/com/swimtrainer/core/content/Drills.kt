    private val byId = all.associateBy { it.id }

    fun byId(id: String): Drill? = byId[id]

    fun forStroke(stroke: Stroke): List<Drill> = all.filter { it.stroke == stroke }

    /** Drills a swimmer at [level] can do for [stroke], ordered by relevance to [focus]. */
    fun suitable(stroke: Stroke, level: Level, focus: DrillFocus? = null): List<Drill> {
        val pool = all.filter {
            (it.stroke == stroke || (it.stroke == Stroke.CHOICE && stroke != Stroke.IM)) &&
                it.minLevel <= level && it.repDistance > 0 && DrillFocus.TURNS !in it.focus
        }
        return if (focus == null) pool else pool.sortedByDescending { focus in it.focus }
    }
